[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string]$InstallDirectory,
    [switch]$IdentityOnly,
    [switch]$PrepareInstall,
    [switch]$CleanupInstallResources
)

$ErrorActionPreference = 'Stop'
Add-Type -TypeDefinition @'
using System.Runtime.InteropServices;
using System.Text;
public static class TrailSnapInstallerPaths {
    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    public static extern uint GetLongPathName(string path, StringBuilder buffer, uint length);
}
'@
function Get-LongPath([string]$Path) {
    $fullPath = [IO.Path]::GetFullPath($Path)
    $buffer = New-Object Text.StringBuilder 32768
    $length = [TrailSnapInstallerPaths]::GetLongPathName($fullPath, $buffer, $buffer.Capacity)
    if ($length -gt 0 -and $length -lt $buffer.Capacity) { return $buffer.ToString() }
    return $fullPath
}
$installRoot = (Get-LongPath $InstallDirectory).TrimEnd('\') + '\'
if ($installRoot -eq [IO.Path]::GetPathRoot($installRoot)) {
    throw 'Refusing to stop processes for a drive root.'
}
if ($IdentityOnly) {
    $hash = [Security.Cryptography.SHA256]::Create()
    try { [BitConverter]::ToString($hash.ComputeHash([Text.Encoding]::UTF8.GetBytes($installRoot.ToLowerInvariant()))).Replace('-', '').ToLowerInvariant() }
    finally { $hash.Dispose() }
    exit 0
}

# PyInstaller's bootloader and runtime are separate processes. Detect either
# process even when the window has already closed. Match installation paths,
# never global image names or another instance's directory.
function Get-InstalledProcesses {
    @(Get-CimInstance Win32_Process | Where-Object {
        $_.ExecutablePath -and
        (Get-LongPath $_.ExecutablePath).StartsWith($installRoot, [StringComparison]::OrdinalIgnoreCase) -and
        $_.Name -in @('TrailSnap.exe', 'portable-launcher.exe', 'trailsnap-desktop.exe', 'trailsnap-server.exe', 'trailsnap-ai.exe', 'llama-server.exe')
    })
}

# Closing a window also terminates its sidecars. An installer cannot know
# whether uploads or file/database transactions have finished, so fail closed.
if (@(Get-InstalledProcesses).Count -gt 0) {
    throw 'TrailSnap is still running. Use Settings > Photos and data location > Safely exit, then run setup again. Background tasks must finish before installing.'
}
if ($PrepareInstall -or $CleanupInstallResources) {
    # NSIS overwrites individual resources but does not remove obsolete files.
    # Rebuild the temporary program resources from a clean directory, otherwise
    # older DLLs and generated bytecode change the offered build's identity.
    $server = [IO.Path]::GetFullPath((Join-Path $installRoot 'server')).TrimEnd('\')
    if (-not $server.StartsWith($installRoot, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'Program resources escaped the selected installation.'
    }
    if ($CleanupInstallResources) {
        # Only remove the temporary payload after the versioned runtime exists.
        $distribution = Get-Content -LiteralPath (Join-Path $installRoot 'portable.json') -Raw | ConvertFrom-Json
        $build = [string]$distribution.activeBuild
        if (!$build -or $build -notmatch '^[a-zA-Z0-9][a-zA-Z0-9._-]*$') {
            throw 'Invalid installed build identity; temporary resources were preserved.'
        }
        $program = Join-Path $installRoot ('app\' + $build)
        foreach ($file in @('manifest.json', 'trailsnap-desktop.exe', 'server\trailsnap-server.exe')) {
            if (!(Test-Path -LiteralPath (Join-Path $program $file) -PathType Leaf)) {
                throw 'Installed runtime is incomplete; temporary resources were preserved.'
            }
        }
    }
    $descriptor = Join-Path $installRoot 'instance.json'
    if (Test-Path -LiteralPath $descriptor) {
        $config = Get-Content -LiteralPath $descriptor -Raw | ConvertFrom-Json
        $data = if ($config.dataRoot.kind -eq 'relative') { Join-Path $installRoot $config.dataRoot.path } else { $config.dataRoot.path }
        $data = (Get-LongPath $data).TrimEnd('\')
        if ($data -eq $server -or $data.StartsWith($server + '\', [StringComparison]::OrdinalIgnoreCase)) {
            throw 'The configured library is inside server. Move the library before installing; no files were removed.'
        }
    }
    if (Test-Path -LiteralPath $server) {
        $entry = Get-Item -LiteralPath $server
        if ($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Linked program resources cannot be replaced.' }
        $entries = @(Get-ChildItem -LiteralPath $server -Recurse -Force)
        if ($entries | Where-Object { $_.Attributes -band [IO.FileAttributes]::ReparsePoint -or $_.Name -in @('trailsnap.sqlite', 'library.json') } | Select-Object -First 1) {
            throw 'Program resources contain a library or link. Preserve the folder and move the library before installing.'
        }
        Remove-Item -LiteralPath $server -Recurse -Force
    }
}
exit 0
