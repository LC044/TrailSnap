# _apply_date_filter
# -------------------------------------------------------------------------


def test_apply_date_filter_returns_query_unchanged_when_no_dates():
    query = MagicMock(name="query")

    result = crud_ls._apply_date_filter(query, None, None)

    assert result is query
    query.filter.assert_not_called()


def test_apply_date_filter_applies_start_date_only():
    query = MagicMock(name="query")
    after_filter = MagicMock(name="after_filter")
    query.filter.return_value = after_filter

    result = crud_ls._apply_date_filter(query, "2026-01-01", None)

    assert result is after_filter
    # One .filter() call carrying the start_date literal.
    query.filter.assert_called_once()
    bound = query.filter.call_args.args[0].right.value
    assert bound == "2026-01-01"


def test_apply_date_filter_applies_end_date_only():
    query = MagicMock(name="query")
    after_filter = MagicMock(name="after_filter")
    query.filter.return_value = after_filter

    result = crud_ls._apply_date_filter(query, None, "2026-12-31")

    assert result is after_filter
    query.filter.assert_called_once()
    bound = query.filter.call_args.args[0].right.value
    assert bound == "2026-12-31 23:59:59"


def test_apply_date_filter_chains_start_then_end():
    query = MagicMock(name="query")
    intermediate = MagicMock(name="intermediate")
    after_end = MagicMock(name="after_end")
    # query.filter() -> intermediate; intermediate.filter() -> after_end.
    query.filter.return_value = intermediate
    intermediate.filter.return_value = after_end

    result = crud_ls._apply_date_filter(query, "2026-01-01", "2026-12-31")

    assert result is after_end
    assert query.filter.call_count == 1
    assert intermediate.filter.call_count == 1


