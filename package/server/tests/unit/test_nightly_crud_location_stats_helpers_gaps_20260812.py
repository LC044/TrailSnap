def test_travel_distance_returns_zero_for_no_rows():
    assert crud_ls._travel_distance([]) == 0


def test_travel_distance_returns_zero_for_single_centroid():
    rows = [SimpleNamespace(lat=30.5, lng=114.3)]
    assert crud_ls._travel_distance(rows) == 0


def test_travel_distance_skips_sub_kilometre_jitter():
    rows = [
        SimpleNamespace(lat=30.5000, lng=114.3000),
        SimpleNamespace(lat=30.5001, lng=114.3001),
    ]
    assert crud_ls._travel_distance(rows) == 0


def test_travel_distance_sums_multi_segment_journey():
    rows = [
        SimpleNamespace(lat=30.5000, lng=114.3000),  # Wuhan
        SimpleNamespace(lat=31.2304, lng=121.4737),  # Shanghai
        SimpleNamespace(lat=39.9042, lng=116.4074),  # Beijing
    ]
    total = crud_ls._travel_distance(rows)
    # Wuhan -> Shanghai + Shanghai -> Beijing > 1700 km.
    assert total > 1700


def test_travel_distance_handles_mixed_jitter_and_real_jump():
    rows = [
        SimpleNamespace(lat=30.5000, lng=114.3000),  # Wuhan
        SimpleNamespace(lat=30.5001, lng=114.3001),  # jitter, ignored
        SimpleNamespace(lat=31.2304, lng=121.4737),  # Shanghai
    ]
    total = crud_ls._travel_distance(rows)
    # Only Wuhan -> Shanghai counts; Shanghai distance ~ 689 km.
    assert 680 <= total <= 700
