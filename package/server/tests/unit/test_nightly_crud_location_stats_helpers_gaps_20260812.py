# -------------------------------------------------------------------------
# _haversine
# -------------------------------------------------------------------------


def test_haversine_returns_zero_for_identical_points():
    assert crud_ls._haversine(30.5, 114.3, 30.5, 114.3) == 0


def test_haversine_matches_known_shanghai_to_beijing_distance():
    # Shanghai (31.2304, 121.4737) -> Beijing (39.9042, 116.4074) ~ 1067 km
    distance = crud_ls._haversine(31.2304, 121.4737, 39.9042, 116.4074)
    assert 1050 <= distance <= 1080


def test_haversine_symmetric_in_arguments():
    forward = crud_ls._haversine(31.2304, 121.4737, 39.9042, 116.4074)
    reverse = crud_ls._haversine(39.9042, 116.4074, 31.2304, 121.4737)
    assert abs(forward - reverse) < 0.01


